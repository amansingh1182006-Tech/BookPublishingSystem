// wwwroot/js/components/AddCategoryForm.js

function AddCategoryForm({ onSuccess, onCancel }) {
    const [categoryNameInput, setCategoryNameInput] = React.useState('');
    const [descriptionInput, setDescriptionInput] = React.useState('');
    const [isSaving, setIsSaving] = React.useState(false);

    const handleSaveCategory = async (e) => {
        e.preventDefault();
        const trimmedName = categoryNameInput.trim();
        if (!trimmedName) {
            alert("Category Name zaroori hai!");
            return;
        }

        // Silent background code generation (UI se completely hidden)
        const autoGeneratedCode = "CAT_" + Math.random().toString(36).substring(2, 7).toUpperCase();

        setIsSaving(true);
        try {
            const res = await fetch('/api/category/create', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    categoryCode: autoGeneratedCode,
                    categoryName: trimmedName,
                    description: descriptionInput.trim()
                })
            });

            const data = await res.json();
            if (res.ok) {
                onSuccess(`Category '${trimmedName}' safaltapoorvak save ho gayi!`);
            } else {
                alert(data.message || "Category add karne me error aaya.");
            }
        } catch (err) {
            alert("Connection error: " + err.message);
        } finally {
            setIsSaving(false);
        }
    };

    return (
        <div className="w-full bg-white p-6 rounded-lg shadow-lg border border-slate-200 space-y-6">
            <div className="flex items-center gap-3 border-b pb-3">
                <button
                    type="button"
                    onClick={onCancel}
                    title="Back to Master List"
                    className="bg-slate-200 hover:bg-slate-300 text-slate-800 font-bold p-2.5 rounded-full text-sm cursor-pointer flex items-center justify-center transition shadow-sm">
                    <i className="fa-solid fa-arrow-left"></i>
                </button>
                <h3 className="text-xl font-bold text-[#0d233a] flex items-center gap-2">
                    <i className="fa-solid fa-user-pen text-blue-600"></i> Add New Category
                </h3>
            </div>

            <form onSubmit={handleSaveCategory} className="space-y-4 text-xs max-w-2xl">
                <div>
                    <label className="font-bold text-slate-700 block mb-1">Category Name *</label>
                    <input
                        type="text"
                        required
                        value={categoryNameInput}
                        onChange={e => setCategoryNameInput(e.target.value)}
                        placeholder="e.g. Clinical Reference"
                        className="w-full border rounded px-3 py-2.5 font-bold outline-none focus:border-amber-600"
                    />
                </div>

                <div>
                    <label className="font-bold text-slate-700 block mb-1">Description / Details</label>
                    <textarea
                        rows="3"
                        value={descriptionInput}
                        onChange={e => setDescriptionInput(e.target.value)}
                        placeholder="System Category details..."
                        className="w-full border rounded px-3 py-2.5 outline-none focus:border-amber-600"
                    ></textarea>
                </div>

                <div className="flex justify-start gap-3 pt-4 border-t">
                    <button
                        type="button"
                        onClick={onCancel}
                        className="bg-slate-200 hover:bg-slate-300 text-slate-700 font-bold px-6 py-2 rounded text-xs cursor-pointer">
                        Cancel
                    </button>
                    <button
                        type="submit"
                        disabled={isSaving}
                        className="bg-amber-600 hover:bg-amber-700 text-white font-bold px-6 py-2 rounded text-xs shadow cursor-pointer flex items-center gap-2">
                        <i className="fa-solid fa-plus"></i>
                        {isSaving ? 'Saving Category...' : 'Save Category Master'}
                    </button>
                </div>
            </form>
        </div>
    );
}
window.AddCategoryForm = AddCategoryForm;